"""
src/experiments/drive_chain.py

The drive model as a MARKOV CHAIN over field position, rather than a bag of
independent drives.

EXPERIMENTAL. Writes nothing; production is untouched.

--------------------------------------------------------------- the idea

drive_model_v2 treats every drive as an independent draw from a blended outcome
distribution. That is wrong in a specific and consequential way: in football,
where a drive STARTS is determined by how the previous drive ENDED. Field
position is not an exogenous team trait to be forecast -- it is a state variable
the game generates.

Measured, 43k drives -- outcome of drive N against where the opponent then
starts drive N+1:

    Punt                 own 24.2   (sd 14.3)
    Touchdown            own 27.2   (sd  7.9)   kickoff, tight
    Field goal           own 26.9   (sd  7.2)   kickoff, tight
    Turnover             own 47.8   (sd 25.1)   <- 23 yards better than a punt
    Turnover on downs    own 37.8   (sd 21.8)
    Missed field goal    own 36.6   (sd  8.5)

Outcome type explains R^2 = 0.347 of the next starting position.

This exposes a real error in v2: a turnover scores ZERO POINTS and the model
stops there. It never accounts for handing the opponent the ball 23 yards
further upfield, worth about 0.8 points at the measured slope. Same for a missed
field goal against a punt -- 12 yards of difference, invisible to v2.

The chain fixes that by construction. It also produces something v2 cannot: a
score distribution in which the two teams' scores are CORRELATED, because they
are generated by the same alternating possession sequence.

------------------------------------------------- why this is not circular

The obvious worry is that chaining predictions compounds errors -- one bad drive
forecast poisons everything after it.

It would, if the chain were SAMPLED. It is not. The expectation is computed by
propagating the state DISTRIBUTION forward exactly:

    outcome_dist = state_dist @ P(outcome | bin)
    points      += outcome_dist @ POINTS
    state_dist'  = outcome_dist @ P(next bin | outcome)

No draws, no variance, no compounding of sampling noise. Model error still
propagates, but the chain is strongly mixing -- every score resets field
position to a kickoff, which is most drives -- so it forgets its own errors
rather than accumulating them. `simulate_games` is available separately when a
distribution rather than an expectation is wanted.

------------------------------------------------------------ honest prior

The mechanism is right and the structure is better. The measured expectation is
still that the POINT prediction barely moves, for a reason one level deeper than
the field-position null:

    prior turnover rate -> future turnover rate   r = +0.067

The chain propagates turnover-driven field position correctly, but a team's
turnover rate is itself almost unpredictable -- the project's own "turnover
luck" finding. The channel is real; its inputs are noise. Incremental R^2 of own
prior turnover rate on points conceded, out of sample: +0.00007.

So this is built for the representation and the distribution, with the point
prediction not expected to move much. Recorded up front so the result is not
read as a surprise either way.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

PBP = "data/raw/pbp.parquet"
SCHEDULES = "data/raw/schedules.parquet"

# Field-position states, in yards to the opponent's end zone. Six bins: enough
# resolution for the EP curve (4.76 down to 1.49) while keeping the smallest bin
# at 662 drives across 7 outcomes, so the conditional table stays well
# determined rather than fitting noise.
BIN_EDGES = [0, 20, 35, 50, 65, 80, 101]
BIN_LABELS = [
    "opp 1-20",
    "opp 21-35",
    "opp 36-50",
    "own 49-35",
    "own 34-20",
    "own 19-1",
]
N_BINS = len(BIN_LABELS)

OUTCOMES = [
    "Touchdown",
    "Field goal",
    "Punt",
    "Turnover",
    "Turnover on downs",
    "Missed field goal",
    "End of half",
    "Opp touchdown",
    "Safety",
]
# Points to the team WITH the ball.
OFFENSE_POINTS = np.array([6.95, 3.0, 0, 0, 0, 0, 0, 0, 0])
# Points to the DEFENDING team -- a return touchdown and a safety.
DEFENSE_POINTS = np.array([0, 0, 0, 0, 0, 0, 0, 6.95, 2.0])

# Possessions per team in a game. Measured mean is 10.93.
DRIVES_PER_TEAM = 11
EPS = 1e-9


def _bin_of(start_100: np.ndarray) -> np.ndarray:
    return np.clip(np.digitize(start_100, BIN_EDGES[1:-1], right=False), 0, N_BINS - 1)


def extract_chain_data(pbp: pd.DataFrame | None = None) -> pd.DataFrame:
    """Drives with their starting bin, outcome, and the NEXT drive's bin."""
    if pbp is None:
        pbp = pd.read_parquet(
            PBP,
            columns=[
                "game_id",
                "play_id",
                "drive",
                "posteam",
                "defteam",
                "down",
                "yardline_100",
                "fixed_drive_result",
            ],
        )
    scrim = pbp[
        pbp["down"].notna()
        & pbp["yardline_100"].notna()
        & pbp["posteam"].notna()
        & pbp["drive"].notna()
    ].sort_values(["game_id", "play_id"])

    d = (
        scrim.groupby(["game_id", "posteam", "defteam", "drive"])
        .agg(start=("yardline_100", "first"), result=("fixed_drive_result", "first"))
        .reset_index()
        .sort_values(["game_id", "drive"])
    )
    d["bin"] = _bin_of(d["start"].to_numpy(float))
    d["next_start"] = d.groupby("game_id")["start"].shift(-1)
    d["next_team"] = d.groupby("game_id")["posteam"].shift(-1)
    d["possession_changed"] = d["next_team"] != d["posteam"]
    d["next_bin"] = np.where(
        d["next_start"].notna(), _bin_of(d["next_start"].fillna(75).to_numpy(float)), -1
    )
    return d


def outcome_given_bin(d: pd.DataFrame) -> np.ndarray:
    """P(outcome | starting bin). Shape (N_BINS, len(OUTCOMES))."""
    t = pd.crosstab(d["bin"], d["result"])
    t = (
        t.reindex(index=range(N_BINS), columns=OUTCOMES, fill_value=0)
        .to_numpy(float)
        .copy()
    )
    t += EPS
    return t / t.sum(axis=1, keepdims=True)


def bin_given_outcome(d: pd.DataFrame) -> np.ndarray:
    """P(next drive's bin | this drive's outcome). Shape (len(OUTCOMES), N_BINS).

    Only transitions where possession actually changed -- a drive followed by
    the same team having the ball is a data artefact, not a football event.
    """
    t = d[d["possession_changed"] & (d["next_bin"] >= 0)]
    c = pd.crosstab(t["result"], t["next_bin"])
    c = (
        c.reindex(index=OUTCOMES, columns=range(N_BINS), fill_value=0)
        .to_numpy(float)
        .copy()
    )
    c += EPS
    return c / c.sum(axis=1, keepdims=True)


def opening_distribution(d: pd.DataFrame) -> np.ndarray:
    """Where a game's first drive starts. The chain's initial state."""
    first = d.groupby("game_id").head(1)
    counts = np.bincount(first["bin"].to_numpy(int), minlength=N_BINS).astype(float)
    counts += EPS
    return counts / counts.sum()


def apply_team_quality(
    cond: np.ndarray, team_marginal: np.ndarray, league_marginal: np.ndarray
) -> np.ndarray:
    """Tilt a league conditional table toward a team's own outcome tendencies.

    P_team(outcome | bin)  proportional to  P_league(outcome | bin) * ratio

    with ratio = team marginal / league marginal. This keeps the field-position
    STRUCTURE (which is measured on 43k drives and is not team-specific) while
    scaling by team quality (which is). Estimating a separate conditional table
    per team would be 32 x 6 x 9 parameters on 1,300 drives each -- exactly the
    overfitting this project keeps finding.
    """
    ratio = np.where(
        league_marginal > EPS, team_marginal / (league_marginal + EPS), 1.0
    )
    out = cond * ratio[None, :]
    return out / out.sum(axis=1, keepdims=True)


def expected_points(
    home_cond: np.ndarray,
    away_cond: np.ndarray,
    transition: np.ndarray,
    opening: np.ndarray,
    drives_per_team: int = DRIVES_PER_TEAM,
) -> tuple[float, float]:
    """Exact expected score for both teams by forward propagation.

    No sampling. The state distribution is carried forward analytically, so the
    chain contributes no variance of its own to the point prediction -- which is
    the whole reason this is not circular.
    """
    home_pts = away_pts = 0.0
    state = opening.copy()
    home_has_ball = True

    for _ in range(2 * drives_per_team):
        cond = home_cond if home_has_ball else away_cond
        outcome = state @ cond
        off = float(outcome @ OFFENSE_POINTS)
        deff = float(outcome @ DEFENSE_POINTS)
        if home_has_ball:
            home_pts += off
            away_pts += deff
        else:
            away_pts += off
            home_pts += deff
        state = outcome @ transition
        home_has_ball = not home_has_ball

    return home_pts, away_pts


def _sample_rows(probs: np.ndarray, rows: np.ndarray, rng) -> np.ndarray:
    """Draw one category per row, where each row uses a DIFFERENT distribution.

    np.random.choice cannot do this vectorised -- it takes a single p. The
    inverse-CDF trick can: take each row's cumulative distribution, draw one
    uniform per row, and count how many cumulative entries it exceeds. Turns a
    Python loop over thousands of trials into one array operation, which is what
    makes a per-game distribution affordable across 1,440 games.
    """
    cdf = probs[rows].cumsum(axis=1)
    cdf[:, -1] = 1.0  # guard against float drift leaving the last bin short
    u = rng.random((len(rows), 1))
    return (u > cdf).sum(axis=1)


def simulate_games(
    home_cond,
    away_cond,
    transition,
    opening,
    n_trials=2000,
    seed=42,
    drives_per_team: int = DRIVES_PER_TEAM,
):
    """Sampled score pairs, for the DISTRIBUTION rather than the mean.

    This is what a chain buys that a regression cannot: the two teams' scores
    come out CORRELATED, because they are generated by one alternating
    possession sequence. Useful for spreads and totals; deliberately not used
    for the point prediction, which has the exact form above.

    Vectorised over trials -- the loop is over the 22 possessions, not the
    thousands of simulations.
    """
    rng = np.random.default_rng(seed)
    home = np.zeros(n_trials)
    away = np.zeros(n_trials)
    state = rng.choice(N_BINS, size=n_trials, p=opening)
    home_has_ball = True

    for _ in range(2 * drives_per_team):
        cond = home_cond if home_has_ball else away_cond
        outcome = _sample_rows(cond, state, rng)
        off = OFFENSE_POINTS[outcome]
        deff = DEFENSE_POINTS[outcome]
        if home_has_ball:
            home += off
            away += deff
        else:
            away += off
            home += deff
        state = _sample_rows(transition, outcome, rng)
        home_has_ball = not home_has_ball

    return home, away


# --------------------------------------------------------- walk-forward model

DRIVE_TABLE = "data/processed/drive_model_table.parquet"
MARGINAL_CATS = [
    "touchdown",
    "field_goal",
    "punt",
    "turnover",
    "turnover_on_downs",
    "missed_field_goal",
    "end_of_half",
    "opp_touchdown",
    "safety",
]


def load_table() -> pd.DataFrame:
    """drive_model_table plus the context columns it lacks (see drive_model_v2)."""
    df = pd.read_parquet(DRIVE_TABLE)
    df["gameday"] = pd.to_datetime(df["gameday"])
    s = pd.read_parquet(SCHEDULES)[["game_id", "location", "overtime"]]
    s["is_neutral_site"] = (s["location"] == "Neutral").astype(int)
    s["went_to_ot"] = s["overtime"].fillna(0).astype(int)
    return df.merge(
        s[["game_id", "is_neutral_site", "went_to_ot"]], on="game_id", how="left"
    )


def _marginal(df: pd.DataFrame, side: str, unit: str) -> np.ndarray:
    cols = [f"{side}_pregame_{unit}_{c}_rate" for c in MARGINAL_CATS]
    m = df[cols].to_numpy(float).copy()
    return m


def fit_chain(train: pd.DataFrame) -> dict:
    """Chain tables and the home edge, from the training fold only.

    The conditional and transition tables are rebuilt from play-by-play
    restricted to games strictly before this fold, so no test-week drive
    contributes to them.
    """
    d = _CHAIN_DATA
    cutoff = train["gameday"].max()
    prior = d[d["gameday"] <= cutoff]
    if len(prior) < 2000:
        prior = d.head(2000)

    cond = outcome_given_bin(prior)
    trans = bin_given_outcome(prior)
    open_ = opening_distribution(prior)
    league = prior["result"].value_counts(normalize=True).reindex(OUTCOMES).fillna(0.0)
    league = (league + EPS).to_numpy(float)
    league = league / league.sum()

    rows = train[train["is_neutral_site"] == 0] if "is_neutral_site" in train else train
    if rows.empty:
        rows = train
    margin = (rows["home_score"] - rows["away_score"]).to_numpy(float)
    w = (
        np.where(rows["went_to_ot"].to_numpy() == 1, 0.5, 1.0)
        if "went_to_ot" in rows
        else None
    )
    home_field = float(
        np.average(margin, weights=w) if w is not None else np.nanmean(margin)
    )

    model = {
        "cond": cond,
        "trans": trans,
        "open": open_,
        "league": league,
        "home_field": home_field,
        "off_h": 0.0,
        "off_a": 0.0,
    }
    from src.models.common import recent_residual_offset

    h, a = predict_chain(model, train)
    model["off_h"], model["off_a"] = recent_residual_offset(train, h, a)
    return model


def predict_chain(model: dict, test: pd.DataFrame):
    cond, trans, open_, league = (
        model["cond"],
        model["trans"],
        model["open"],
        model["league"],
    )
    n = len(test)
    hp = np.zeros(n)
    ap = np.zeros(n)

    ho = _marginal(test, "home", "off")
    ao = _marginal(test, "away", "off")
    hd = _marginal(test, "home", "def")
    ad = _marginal(test, "away", "def")
    for m in (ho, ao, hd, ad):
        bad = ~np.isfinite(m).all(axis=1) | (np.nansum(m, axis=1) <= 0)
        m[bad] = league

    for i in range(n):
        # A team's effective outcome mix is its offence against that defence --
        # the same log5-free proportional blend drive_model_v2 uses, kept simple
        # because the field-position structure is doing the relational work here.
        h_mix = (ho[i] / ho[i].sum() + ad[i] / ad[i].sum()) / 2
        a_mix = (ao[i] / ao[i].sum() + hd[i] / hd[i].sum()) / 2
        hc = apply_team_quality(cond, h_mix, league)
        ac = apply_team_quality(cond, a_mix, league)
        hp[i], ap[i] = expected_points(hc, ac, trans, open_)

    adj = model["home_field"] / 2.0
    if "is_neutral_site" in test.columns:
        adj = adj * (1 - test["is_neutral_site"].to_numpy(float))
    return hp + adj - model["off_h"], ap - adj - model["off_a"]


_CHAIN_DATA = None


def main():
    global _CHAIN_DATA
    from src.validate.walk_forward import score_predictions, walk_forward_evaluate

    d = extract_chain_data()
    sch = pd.read_parquet(SCHEDULES)[["game_id", "gameday"]]
    sch["gameday"] = pd.to_datetime(sch["gameday"])
    _CHAIN_DATA = d.merge(sch, on="game_id", how="left")

    df = load_table()
    res = walk_forward_evaluate(df, fit_chain, predict_chain, min_train_seasons=2)
    m = score_predictions(res)
    print("\nDrive CHAIN walk-forward:")
    for k, v in m.items():
        print(f"  {k}: {v:.3f}" if isinstance(v, float) else f"  {k}: {v}")
    print(f"  mean RMSE: {(m['home_rmse'] + m['away_rmse']) / 2:.4f}")
    print("\n  reference: drive_model_v2 9.4635 | baseline 9.458 | poisson 9.367")
    res.to_parquet("data/processed/drivechain_predictions.parquet", index=False)


if __name__ == "__main__":
    main()
